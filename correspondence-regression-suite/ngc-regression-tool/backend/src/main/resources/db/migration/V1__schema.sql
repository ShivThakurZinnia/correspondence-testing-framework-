-- NGC Regression Suite: application schema (H2 now, Postgres-portable).
-- Portability rules: BIGINT identity keys, VARCHAR/TEXT only (no BLOB/CLOB), TIMESTAMP WITH TIME ZONE,
-- JSON stored as TEXT, no vendor functions. Large artifacts live on disk; the DB keeps path + sha256.

-- ---------------------------------------------------------------- reference data
-- Tags are one table keyed by category so client/event/mapper/priority/path share CRUD and filtering.
CREATE TABLE tag (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category    VARCHAR(20)  NOT NULL,          -- CLIENT | EVENT | MAPPER | PRIORITY | PATH
    code        VARCHAR(60)  NOT NULL,          -- e.g. GILI, policy-page, anniversary
    label       VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tag UNIQUE (category, code),
    CONSTRAINT ck_tag_category CHECK (category IN ('CLIENT','EVENT','MAPPER','PRIORITY','PATH'))
);

-- Target NGC environment (qa, uat...). Connection secrets stay in .env, never here.
CREATE TABLE environment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL UNIQUE,    -- qa, uat, dev
    name       VARCHAR(120) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Kafka topics a tester may choose per env. SOR: zinnia.correspondence.sor ; BPM: zinnia.correspondence.<env>
CREATE TABLE kafka_topic (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id BIGINT       NOT NULL REFERENCES environment(id),
    kind           VARCHAR(10)  NOT NULL,       -- SOR | BPM
    topic_name     VARCHAR(200) NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_kafka_topic UNIQUE (environment_id, topic_name),
    CONSTRAINT ck_kafka_topic_kind CHECK (kind IN ('SOR','BPM'))
);

-- ---------------------------------------------------------------- artifacts (payloads, golden XML, captured output)
CREATE TABLE artifact (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         VARCHAR(30)  NOT NULL,         -- EVENT_PAYLOAD | GOLDEN_XML | RUN_XML | CDS_PAYLOAD | MONGO_SNAPSHOT | REPORT
    name         VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    sha256       VARCHAR(64)  NOT NULL,
    size_bytes   BIGINT       NOT NULL,
    storage      VARCHAR(10)  NOT NULL,         -- DB (small, editable inputs) | FILE (captured output)
    content      TEXT,                          -- when storage = DB
    file_path    VARCHAR(1000),                 -- when storage = FILE, relative to data/artifacts
    created_by   VARCHAR(120),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_artifact_storage CHECK (
        (storage = 'DB' AND content IS NOT NULL) OR (storage = 'FILE' AND file_path IS NOT NULL)),
    CONSTRAINT ck_artifact_kind CHECK (kind IN
        ('EVENT_PAYLOAD','GOLDEN_XML','RUN_XML','CDS_PAYLOAD','MONGO_SNAPSHOT','REPORT'))
);
CREATE INDEX ix_artifact_sha ON artifact(sha256);

-- ---------------------------------------------------------------- test modules and versions (immutable)
CREATE TABLE test_module (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(60)  NOT NULL UNIQUE,   -- policy-page
    name        VARCHAR(160) NOT NULL,
    description VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A snapshot of the module. Never updated except `status`; any content change makes a new row.
CREATE TABLE module_version (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id    BIGINT       NOT NULL REFERENCES test_module(id),
    version_no   INT          NOT NULL,         -- 1,2,3... monotonic per module
    version      VARCHAR(20)  NOT NULL,         -- semver label shown to users, e.g. 1.4.0
    content_hash VARCHAR(64)  NOT NULL,         -- sha256 over member test_case_version hashes (detects no-op saves)
    status       VARCHAR(15)  NOT NULL DEFAULT 'DRAFT',   -- DRAFT | APPROVED | RELEASE_GATE | RETIRED
    change_note  VARCHAR(1000) NOT NULL,
    created_by   VARCHAR(120) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_by  VARCHAR(120),
    approved_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_module_version_no UNIQUE (module_id, version_no),
    CONSTRAINT uq_module_version_label UNIQUE (module_id, version),
    CONSTRAINT ck_module_version_status CHECK (status IN ('DRAFT','APPROVED','RELEASE_GATE','RETIRED'))
);

-- Stable identity of a scenario across versions.
CREATE TABLE test_case (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id    BIGINT       NOT NULL REFERENCES test_module(id),
    scenario_key VARCHAR(120) NOT NULL,         -- gili-policy-page-owner-print
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_test_case UNIQUE (module_id, scenario_key)
);

-- Immutable definition of one scenario at one point in time.
CREATE TABLE test_case_version (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_case_id        BIGINT        NOT NULL REFERENCES test_case(id),
    revision            INT           NOT NULL,           -- 1,2,3 per test case
    name                VARCHAR(200)  NOT NULL,
    description         VARCHAR(1000),
    kafka_kind          VARCHAR(10)   NOT NULL,           -- SOR | BPM : tester-chosen, mandatory
    kafka_topic_pattern VARCHAR(200)  NOT NULL,           -- zinnia.correspondence.sor | zinnia.correspondence.{env}
    event_type          VARCHAR(120)  NOT NULL,           -- EventModel.type, e.g. policy.activation.completed
    carrier             VARCHAR(30)   NOT NULL,           -- EventModel.carrier, e.g. GILI
    plan_code           VARCHAR(30),
    payload_artifact_id BIGINT        NOT NULL REFERENCES artifact(id),   -- uploaded EventModel JSON
    golden_artifact_id  BIGINT        REFERENCES artifact(id),            -- optional golden XML
    expected_json       TEXT          NOT NULL,           -- assertions (see docs/SCHEMA.md)
    timeout_seconds     INT           NOT NULL DEFAULT 600,
    enabled             BOOLEAN       NOT NULL DEFAULT TRUE,
    content_hash        VARCHAR(64)   NOT NULL,
    change_note         VARCHAR(1000),
    created_by          VARCHAR(120)  NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_test_case_revision UNIQUE (test_case_id, revision),
    CONSTRAINT ck_tcv_kind CHECK (kafka_kind IN ('SOR','BPM')),
    CONSTRAINT ck_tcv_timeout CHECK (timeout_seconds > 0)
);

CREATE TABLE test_case_version_tag (
    test_case_version_id BIGINT NOT NULL REFERENCES test_case_version(id),
    tag_id               BIGINT NOT NULL REFERENCES tag(id),
    PRIMARY KEY (test_case_version_id, tag_id)
);
CREATE INDEX ix_tcvt_tag ON test_case_version_tag(tag_id);

-- Which scenario revisions make up a module version (unchanged revisions are shared, not copied).
CREATE TABLE module_version_case (
    module_version_id    BIGINT NOT NULL REFERENCES module_version(id),
    test_case_version_id BIGINT NOT NULL REFERENCES test_case_version(id),
    PRIMARY KEY (module_version_id, test_case_version_id)
);

-- ---------------------------------------------------------------- schedules
CREATE TABLE schedule (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(160) NOT NULL UNIQUE,
    module_id         BIGINT       NOT NULL REFERENCES test_module(id),
    module_version_id BIGINT       REFERENCES module_version(id),   -- NULL = follow latest APPROVED
    environment_id    BIGINT       NOT NULL REFERENCES environment(id),
    tag_expression    VARCHAR(500),                                  -- e.g. client:GILI,event:policy-page
    cron_expression   VARCHAR(100) NOT NULL,
    timezone          VARCHAR(60)  NOT NULL DEFAULT 'UTC',
    overlap_policy    VARCHAR(10)  NOT NULL DEFAULT 'SKIP',          -- SKIP | QUEUE
    notify_target     VARCHAR(500),
    enabled           BOOLEAN      NOT NULL DEFAULT TRUE,
    last_fired_at     TIMESTAMP WITH TIME ZONE,
    created_by        VARCHAR(120) NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_schedule_overlap CHECK (overlap_policy IN ('SKIP','QUEUE'))
);

-- ---------------------------------------------------------------- runs and results
CREATE TABLE test_run (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_key           VARCHAR(40)  NOT NULL UNIQUE,                  -- UUID, shown in reports
    module_version_id BIGINT       NOT NULL REFERENCES module_version(id),   -- pins exact version used
    environment_id    BIGINT       NOT NULL REFERENCES environment(id),
    trigger_source    VARCHAR(10)  NOT NULL,                         -- UI | CLI | SCHEDULE | MCP | CI
    schedule_id       BIGINT       REFERENCES schedule(id),
    triggered_by      VARCHAR(120),
    tag_expression    VARCHAR(500),
    status            VARCHAR(12)  NOT NULL,                         -- QUEUED | RUNNING | PASSED | FAILED | ERROR | CANCELLED
    queued_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at        TIMESTAMP WITH TIME ZONE,
    finished_at       TIMESTAMP WITH TIME ZONE,
    runner_version    VARCHAR(40),
    ngc_build_version VARCHAR(80),                                   -- observed from the target env at run time
    rule_set_version  VARCHAR(80),
    total_cases       INT NOT NULL DEFAULT 0,
    passed_cases      INT NOT NULL DEFAULT 0,
    failed_cases      INT NOT NULL DEFAULT 0,
    report_artifact_id BIGINT REFERENCES artifact(id),
    CONSTRAINT ck_run_trigger CHECK (trigger_source IN ('UI','CLI','SCHEDULE','MCP','CI')),
    CONSTRAINT ck_run_status CHECK (status IN ('QUEUED','RUNNING','PASSED','FAILED','ERROR','CANCELLED'))
);
CREATE INDEX ix_run_env_time ON test_run(environment_id, queued_at);
CREATE INDEX ix_run_module_version ON test_run(module_version_id);
CREATE INDEX ix_run_schedule ON test_run(schedule_id);

CREATE TABLE test_run_case (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                BIGINT       NOT NULL REFERENCES test_run(id),
    test_case_version_id  BIGINT       NOT NULL REFERENCES test_case_version(id),
    correlation_id        VARCHAR(80)  NOT NULL,                      -- fresh, marker-prefixed UUID injected into NGC
    ngc_unique_id         VARCHAR(80),                                -- incoming_events.uniqueId once seen
    topic_name            VARCHAR(200) NOT NULL,                      -- resolved topic actually used
    status                VARCHAR(10)  NOT NULL,                      -- PENDING | RUNNING | PASSED | FAILED | ERROR | TIMEOUT | SKIPPED
    final_incoming_status VARCHAR(40),                                -- incoming_events.status observed at end
    failure_summary       VARCHAR(2000),
    started_at            TIMESTAMP WITH TIME ZONE,
    finished_at           TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_run_case_corr UNIQUE (correlation_id),
    CONSTRAINT ck_run_case_status CHECK (status IN ('PENDING','RUNNING','PASSED','FAILED','ERROR','TIMEOUT','SKIPPED'))
);
CREATE INDEX ix_run_case_run ON test_run_case(run_id);
CREATE INDEX ix_run_case_tcv ON test_run_case(test_case_version_id, started_at);

CREATE TABLE assertion_result (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_case_id BIGINT       NOT NULL REFERENCES test_run_case(id),
    category    VARCHAR(20)  NOT NULL,   -- INCOMING_EVENT | TARGET | XML | CDS | JOURNEY | CALLBACK | NO_FAILURE
    path        VARCHAR(300) NOT NULL,   -- e.g. targets[OWNER].deliveryType
    expected    VARCHAR(2000),
    actual      VARCHAR(2000),
    passed      BOOLEAN      NOT NULL,
    message     VARCHAR(1000)
);
CREATE INDEX ix_assert_case ON assertion_result(run_case_id);

-- Observed timeline for a run case: Kafka in, Mongo status changes, S3 object seen, callbacks received.
CREATE TABLE run_observation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_case_id   BIGINT       NOT NULL REFERENCES test_run_case(id),
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    source        VARCHAR(10)  NOT NULL,   -- KAFKA | MONGO | S3
    collection    VARCHAR(60),             -- incoming_events, event_journey, internal_events, cds_events ...
    event_type    VARCHAR(120),
    status        VARCHAR(40),
    target_role   VARCHAR(40),
    detail_json   TEXT                     -- masked, structural fields only
);
CREATE INDEX ix_obs_case_time ON run_observation(run_case_id, occurred_at);

CREATE TABLE run_case_artifact (
    run_case_id BIGINT      NOT NULL REFERENCES test_run_case(id),
    artifact_id BIGINT      NOT NULL REFERENCES artifact(id),
    role        VARCHAR(30) NOT NULL,      -- GENERATED_XML | CDS_PAYLOAD | SNAPSHOT
    PRIMARY KEY (run_case_id, artifact_id)
);

-- ---------------------------------------------------------------- environment health (dashboard trends)
CREATE TABLE health_snapshot (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id BIGINT       NOT NULL REFERENCES environment(id),
    captured_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    metric_key     VARCHAR(60)  NOT NULL,  -- STUCK_PROCESSING | TECH_FAILURE_RATE | RETRY_EXHAUSTED | DEAD_LETTER_BACKLOG | FUNNEL_SENT_TO_CDS ...
    dimension      VARCHAR(200),           -- carrier:eventType, workerName, ...
    metric_value   DOUBLE PRECISION NOT NULL,
    detail_json    TEXT
);
CREATE INDEX ix_health_env_metric ON health_snapshot(environment_id, metric_key, captured_at);

-- ---------------------------------------------------------------- audit
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(40)  NOT NULL,     -- TAG | MODULE_VERSION | SCHEDULE | ENVIRONMENT ...
    entity_id   BIGINT       NOT NULL,
    action      VARCHAR(20)  NOT NULL,     -- CREATE | UPDATE | DEACTIVATE | APPROVE
    actor       VARCHAR(120) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    detail_json TEXT
);
CREATE INDEX ix_audit_entity ON audit_log(entity_type, entity_id);
